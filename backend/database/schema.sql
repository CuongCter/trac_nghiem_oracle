-- Oracle 19c Schema for He thong Quan ly Thi Trac Nghiem
-- Identifiers are quoted to keep them in upper case to match the application queries.

-- USERS -----------------------------------------------------------
CREATE TABLE USERS (
  ID              NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  FULL_NAME       VARCHAR2(120 CHAR)  NOT NULL,
  EMAIL           VARCHAR2(180 CHAR)  NOT NULL,
  PASSWORD_HASH   VARCHAR2(255 CHAR)  NOT NULL,
  ROLE            VARCHAR2(20 CHAR)   NOT NULL,
  STATUS          VARCHAR2(20 CHAR)   DEFAULT 'ACTIVE' NOT NULL,
  CREATED_AT      TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT      TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT USERS_EMAIL_UN UNIQUE (EMAIL),
  CONSTRAINT USERS_ROLE_CHK CHECK (ROLE IN ('ADMIN','TEACHER','STUDENT')),
  CONSTRAINT USERS_STATUS_CHK CHECK (STATUS IN ('ACTIVE','LOCKED'))
);

-- SUBJECTS --------------------------------------------------------
CREATE TABLE SUBJECTS (
  ID           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  NAME         VARCHAR2(120 CHAR) NOT NULL,
  CODE         VARCHAR2(20 CHAR)  NOT NULL,
  DESCRIPTION  VARCHAR2(500 CHAR),
  CREATED_BY   NUMBER,
  CREATED_AT   TIMESTAMP          DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT   TIMESTAMP          DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT SUBJECTS_CODE_UN UNIQUE (CODE),
  CONSTRAINT SUBJECTS_CREATED_BY_FK FOREIGN KEY (CREATED_BY) REFERENCES USERS(ID) ON DELETE SET NULL
);

-- QUESTIONS -------------------------------------------------------
CREATE TABLE QUESTIONS (
  ID              NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  SUBJECT_ID      NUMBER NOT NULL,
  CONTENT         VARCHAR2(2000 CHAR) NOT NULL,
  OPTION_A        VARCHAR2(500 CHAR)  NOT NULL,
  OPTION_B        VARCHAR2(500 CHAR)  NOT NULL,
  OPTION_C        VARCHAR2(500 CHAR)  NOT NULL,
  OPTION_D        VARCHAR2(500 CHAR)  NOT NULL,
  CORRECT_ANSWER  CHAR(1) NOT NULL,
  DIFFICULTY      VARCHAR2(20 CHAR)   NOT NULL,
  CHAPTER         VARCHAR2(80 CHAR),
  POINT           NUMBER(6,2)         DEFAULT 1 NOT NULL,
  CREATED_BY      NUMBER,
  CREATED_AT      TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT      TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT QUESTIONS_SUBJECT_FK FOREIGN KEY (SUBJECT_ID) REFERENCES SUBJECTS(ID) ON DELETE CASCADE,
  CONSTRAINT QUESTIONS_CREATED_BY_FK FOREIGN KEY (CREATED_BY) REFERENCES USERS(ID) ON DELETE SET NULL,
  CONSTRAINT QUESTIONS_CORRECT_CHK CHECK (CORRECT_ANSWER IN ('A','B','C','D')),
  CONSTRAINT QUESTIONS_DIFF_CHK CHECK (DIFFICULTY IN ('EASY','MEDIUM','HARD')),
  CONSTRAINT QUESTIONS_POINT_CHK CHECK (POINT > 0 AND POINT <= 100)
);
CREATE INDEX IDX_QUESTIONS_SUBJECT ON QUESTIONS(SUBJECT_ID);
CREATE INDEX IDX_QUESTIONS_DIFFICULTY ON QUESTIONS(SUBJECT_ID, DIFFICULTY);

-- CLASSES ---------------------------------------------------------
CREATE TABLE CLASSES (
  ID          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  NAME        VARCHAR2(120 CHAR) NOT NULL,
  TEACHER_ID  NUMBER,
  CREATED_AT  TIMESTAMP          DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT  TIMESTAMP          DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT CLASSES_NAME_UN UNIQUE (NAME),
  CONSTRAINT CLASSES_TEACHER_FK FOREIGN KEY (TEACHER_ID) REFERENCES USERS(ID) ON DELETE SET NULL
);

CREATE TABLE CLASS_STUDENTS (
  CLASS_ID    NUMBER NOT NULL,
  STUDENT_ID  NUMBER NOT NULL,
  ADDED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT CLASS_STUDENTS_PK PRIMARY KEY (CLASS_ID, STUDENT_ID),
  CONSTRAINT CLASS_STUDENTS_CLASS_FK FOREIGN KEY (CLASS_ID) REFERENCES CLASSES(ID) ON DELETE CASCADE,
  CONSTRAINT CLASS_STUDENTS_USER_FK FOREIGN KEY (STUDENT_ID) REFERENCES USERS(ID) ON DELETE CASCADE
);
CREATE INDEX IDX_CLASS_STUDENTS_STUDENT ON CLASS_STUDENTS(STUDENT_ID);

-- EXAMS ------------------------------------------------------------
CREATE TABLE EXAMS (
  ID                 NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  TITLE              VARCHAR2(200 CHAR) NOT NULL,
  SUBJECT_ID         NUMBER NOT NULL,
  DURATION_MINUTES   NUMBER NOT NULL,
  TOTAL_QUESTIONS    NUMBER DEFAULT 0 NOT NULL,
  TOTAL_POINTS       NUMBER(8,2) DEFAULT 0 NOT NULL,
  START_TIME         TIMESTAMP NOT NULL,
  END_TIME           TIMESTAMP NOT NULL,
  STATUS             VARCHAR2(20 CHAR) DEFAULT 'DRAFT' NOT NULL,
  SHUFFLE_QUESTIONS  CHAR(1) DEFAULT 'Y' NOT NULL,
  SHUFFLE_OPTIONS    CHAR(1) DEFAULT 'Y' NOT NULL,
  CREATED_BY         NUMBER,
  CREATED_AT         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT EXAMS_SUBJECT_FK FOREIGN KEY (SUBJECT_ID) REFERENCES SUBJECTS(ID) ON DELETE CASCADE,
  CONSTRAINT EXAMS_CREATED_BY_FK FOREIGN KEY (CREATED_BY) REFERENCES USERS(ID) ON DELETE SET NULL,
  CONSTRAINT EXAMS_STATUS_CHK CHECK (STATUS IN ('DRAFT','PUBLISHED','CLOSED')),
  CONSTRAINT EXAMS_TIME_CHK CHECK (END_TIME > START_TIME),
  CONSTRAINT EXAMS_DURATION_CHK CHECK (DURATION_MINUTES > 0)
);
CREATE INDEX IDX_EXAMS_SUBJECT_STATUS ON EXAMS(SUBJECT_ID, STATUS);
CREATE INDEX IDX_EXAMS_STATUS_START ON EXAMS(STATUS, START_TIME, END_TIME);

CREATE TABLE EXAM_QUESTIONS (
  EXAM_ID      NUMBER NOT NULL,
  QUESTION_ID  NUMBER NOT NULL,
  POSITION     NUMBER,
  CONSTRAINT EXAM_QUESTIONS_PK PRIMARY KEY (EXAM_ID, QUESTION_ID),
  CONSTRAINT EXAM_QUESTIONS_EXAM_FK FOREIGN KEY (EXAM_ID) REFERENCES EXAMS(ID) ON DELETE CASCADE,
  CONSTRAINT EXAM_QUESTIONS_Q_FK FOREIGN KEY (QUESTION_ID) REFERENCES QUESTIONS(ID) ON DELETE CASCADE
);
CREATE INDEX IDX_EXAM_QUESTIONS_Q ON EXAM_QUESTIONS(QUESTION_ID);

CREATE TABLE EXAM_CLASSES (
  EXAM_ID    NUMBER NOT NULL,
  CLASS_ID   NUMBER NOT NULL,
  CONSTRAINT EXAM_CLASSES_PK PRIMARY KEY (EXAM_ID, CLASS_ID),
  CONSTRAINT EXAM_CLASSES_EXAM_FK FOREIGN KEY (EXAM_ID) REFERENCES EXAMS(ID) ON DELETE CASCADE,
  CONSTRAINT EXAM_CLASSES_CLASS_FK FOREIGN KEY (CLASS_ID) REFERENCES CLASSES(ID) ON DELETE CASCADE
);
CREATE INDEX IDX_EXAM_CLASSES_CLASS ON EXAM_CLASSES(CLASS_ID);

-- EXAM ATTEMPTS ---------------------------------------------------
CREATE TABLE EXAM_ATTEMPTS (
  ID                NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  EXAM_ID           NUMBER NOT NULL,
  STUDENT_ID        NUMBER NOT NULL,
  STARTED_AT        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  END_TIME          TIMESTAMP NOT NULL,
  SUBMITTED_AT      TIMESTAMP,
  STATUS            VARCHAR2(20 CHAR) DEFAULT 'IN_PROGRESS' NOT NULL,
  IS_AUTO_SUBMITTED CHAR(1) DEFAULT 'N' NOT NULL,
  CONSTRAINT ATTEMPTS_EXAM_FK FOREIGN KEY (EXAM_ID) REFERENCES EXAMS(ID) ON DELETE CASCADE,
  CONSTRAINT ATTEMPTS_STUDENT_FK FOREIGN KEY (STUDENT_ID) REFERENCES USERS(ID) ON DELETE CASCADE,
  CONSTRAINT ATTEMPTS_STATUS_CHK CHECK (STATUS IN ('IN_PROGRESS','SUBMITTED','EXPIRED')),
  CONSTRAINT ATTEMPTS_UN UNIQUE (EXAM_ID, STUDENT_ID)
);
CREATE INDEX IDX_ATTEMPTS_STUDENT ON EXAM_ATTEMPTS(STUDENT_ID);

CREATE TABLE ATTEMPT_ANSWERS (
  ATTEMPT_ID      NUMBER NOT NULL,
  QUESTION_ID     NUMBER NOT NULL,
  SELECTED_OPTION CHAR(1),
  CONSTRAINT ATTEMPT_ANSWERS_PK PRIMARY KEY (ATTEMPT_ID, QUESTION_ID),
  CONSTRAINT ATTEMPT_ANSWERS_ATTEMPT_FK FOREIGN KEY (ATTEMPT_ID) REFERENCES EXAM_ATTEMPTS(ID) ON DELETE CASCADE,
  CONSTRAINT ATTEMPT_ANSWERS_Q_FK FOREIGN KEY (QUESTION_ID) REFERENCES QUESTIONS(ID) ON DELETE CASCADE,
  CONSTRAINT ATTEMPT_ANSWERS_OPT_CHK CHECK (SELECTED_OPTION IS NULL OR SELECTED_OPTION IN ('A','B','C','D'))
);

-- VIOLATIONS -------------------------------------------------------
CREATE TABLE VIOLATIONS (
  ID          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  ATTEMPT_ID  NUMBER NOT NULL,
  TYPE        VARCHAR2(40 CHAR) NOT NULL,
  OCCURRED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT VIOLATIONS_ATTEMPT_FK FOREIGN KEY (ATTEMPT_ID) REFERENCES EXAM_ATTEMPTS(ID) ON DELETE CASCADE
);
CREATE INDEX IDX_VIOLATIONS_ATTEMPT ON VIOLATIONS(ATTEMPT_ID, OCCURRED_AT);

-- EXAM RESULTS -----------------------------------------------------
CREATE TABLE EXAM_RESULTS (
  ID            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  EXAM_ID       NUMBER NOT NULL,
  STUDENT_ID    NUMBER NOT NULL,
  TOTAL_CORRECT NUMBER DEFAULT 0 NOT NULL,
  TOTAL_WRONG   NUMBER DEFAULT 0 NOT NULL,
  SCORE         NUMBER(6,2) DEFAULT 0 NOT NULL,
  PASSED        CHAR(1) DEFAULT 'N' NOT NULL,
  SUBMITTED_AT  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  GRADED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT RESULTS_EXAM_FK FOREIGN KEY (EXAM_ID) REFERENCES EXAMS(ID) ON DELETE CASCADE,
  CONSTRAINT RESULTS_STUDENT_FK FOREIGN KEY (STUDENT_ID) REFERENCES USERS(ID) ON DELETE CASCADE,
  CONSTRAINT RESULTS_UN UNIQUE (EXAM_ID, STUDENT_ID)
);
CREATE INDEX IDX_RESULTS_STUDENT ON EXAM_RESULTS(STUDENT_ID);

CREATE TABLE RESULT_ANSWERS (
  RESULT_ID       NUMBER NOT NULL,
  QUESTION_ID     NUMBER NOT NULL,
  SELECTED_OPTION CHAR(1),
  IS_CORRECT      CHAR(1) DEFAULT 'N' NOT NULL,
  CONSTRAINT RESULT_ANSWERS_PK PRIMARY KEY (RESULT_ID, QUESTION_ID),
  CONSTRAINT RESULT_ANSWERS_RESULT_FK FOREIGN KEY (RESULT_ID) REFERENCES EXAM_RESULTS(ID) ON DELETE CASCADE,
  CONSTRAINT RESULT_ANSWERS_Q_FK FOREIGN KEY (QUESTION_ID) REFERENCES QUESTIONS(ID) ON DELETE CASCADE
);
